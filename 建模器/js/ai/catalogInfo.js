const hit = (ids, key) => ids.some(i => (i instanceof RegExp ? i.test(key) : i === key));

/**
 * 這一顆的前提、規格、核對。組照「在哪」的開頭配最長的；CLUSTERS 照代號再蓋過去。
 * @param {{代號:string, 在哪:string}} e
 * @returns {{前提:string, 規格:string, 核對:string, 組:string|null}}
 */
export function infoOf(e) {
  let g = null;
  for (const row of GROUPS) if (e.在哪 === row[0] || e.在哪.startsWith(row[0] + '：') || e.在哪.startsWith(row[0] + '／')) if (!g || row[0].length > g[0].length) g = row;
  const out = g ? { 前提: g[1], 規格: g[2], 核對: g[3], 組: g[0] } : { 前提: '', 規格: '', 核對: '', 組: null };
  const key = String(e.代號).replace(/#\d+$/, '');
  for (const c of CLUSTERS) if (hit(c.ids, key)) { if (c.前提) out.前提 = c.前提; if (c.規格) out.規格 = c.規格; }
  return out;
}
